# One entry per model: layer depths, per the paper (all three use a
# 32-layer Whisper-large-v3 encoder; decoder depth follows each model's
# backbone LLM).
MODELS = {
    "Audio Flamingo 3": {"enc_layers": 32, "dec_layers": 28},
    "Qwen2-Audio": {"enc_layers": 32, "dec_layers": 32},
    "Voxtral": {"enc_layers": 32, "dec_layers": 30},
}

# Same color and marker per model regardless of variant; dashed for the
# shortGPT baseline, solid for our method, so paired lines are easy to tell
# apart.
_MODEL_COLORS = dict(zip(MODELS, plt.rcParams["axes.prop_cycle"].by_key()["color"]))
_MODEL_MARKERS = dict(zip(MODELS, ["o", "s", ">"]))
_SHORTGPT_LINESTYLE = ":"
_OURS_LINESTYLE = "-"
_REVERSE_LINESTYLE = "--"

# Column to plot per task -- override with --metric.
DEFAULT_METRIC = {
    "asr": "wer",
    "obqa": "overall_accuracy",
    "mmsu": "overall_accuracy",
}

# (task, subplot title) in the order the panels are drawn, left to right.
TASK_TITLES = [
    ("asr", "Common Voice dataset"),
    ("mmsu", "MMSU dataset"),
    ("obqa", "OBQA dataset"),
]

# label -> (model key, subdirectory holding performance_results_<task>.csv)
DEC = {
    r"Audio Flamingo 3-BI$^{{\cal A}\cup{\cal T}}$": ("Audio Flamingo 3", "audioflamingo3_shortGPT"),
    "Audio Flamingo 3-SBI-Dec": ("Audio Flamingo 3", "audioflamingo3_text_BI+modified_enc_BI"),
    r"Audio Flamingo 3-deepest-$k$": ("Audio Flamingo 3", "audioflamingo3_reverse_BI+modified_enc_BI"),
    r"Qwen2-Audio-BI$^{{\cal A}\cup{\cal T}}$": ("Qwen2-Audio", "qwen2audio_shortGPT"),
    "Qwen2-Audio-SBI-Dec": ("Qwen2-Audio", "qwen2audio_text_BI+modified_enc_BI"),
    r"Qwen2-Audio-deepest-$k$": ("Qwen2-Audio", "qwen2audio_reverse_BI+modified_enc_BI"),
    r"Voxtral-BI$^{{\cal A}\cup{\cal T}}$": ("Voxtral", "voxtral_shortGPT"),
    "Voxtral-SBI-Dec": ("Voxtral", "voxtral_text_BI+modified_enc_BI"),
    r"Voxtral-deepest-$k$": ("Voxtral", "voxtral_reverse_BI+modified_enc_BI"),
}
ENC = {
    "Audio Flamingo 3-BI": ("Audio Flamingo 3", "audioflamingo3_shortGPT"),
    "Audio Flamingo 3-SBI-Enc": ("Audio Flamingo 3", "audioflamingo3_text_BI+modified_enc_BI"),
    "Qwen2-Audio-BI": ("Qwen2-Audio", "qwen2audio_shortGPT"),
    "Qwen2-Audio-SBI-Enc": ("Qwen2-Audio", "qwen2audio_text_BI+modified_enc_BI"),
    "Voxtral-BI": ("Voxtral", "voxtral_shortGPT"),
    "Voxtral-SBI-Enc": ("Voxtral", "voxtral_text_BI+modified_enc_BI"),
}



def plot_all_tasks(component, other_removed=0, results_dir=None, save_path=None):
    """
    One figure, three panels side by side (Common Voice / MMSU / OBQA),
    all driven by the same component's ('enc' or 'dec') removal percentage,
    with a single legend shared across all three.
    """
    results_dir = results_dir or os.environ.get("RESULTS_DIR")
    if not results_dir:
        raise ValueError("Environment variable RESULTS_DIR is not set")

    RUN = DEC if component == "dec" else ENC
    # Both legends have too many entries for one line; give them two rows
    # and extra figure height so they don't overlap the panels above.
    two_row_legend = True

    fig, axes = plt.subplots(1, len(TASK_TITLES),
                             figsize=(6.5 * len(TASK_TITLES), 5.1 if two_row_legend else 4.5))

    prev_metric_label = None
    for ax, (task, title) in zip(axes, TASK_TITLES):
        files = {
            label: {
                "path": os.path.join(results_dir, subdir, f"{task}.csv"),
                **MODELS[model],
                "color": _MODEL_COLORS[model],
                "marker": _MODEL_MARKERS[model],
                "linestyle": _SHORTGPT_LINESTYLE if "shortGPT" in subdir else _REVERSE_LINESTYLE if "reverse" in subdir else _OURS_LINESTYLE,
            }
            for label, (model, subdir) in RUN.items()
        }

        metric = DEFAULT_METRIC[task]
        # Cap error-like metrics so a blown-up run doesn't squash the rest;
        # accuracies sit in [0, 1] on their own and are left to autoscale.
        is_error = "wer" in metric or "error" in metric
        cap = 100 if is_error else None

        # Only label the y axis when it differs from the panel to its left,
        # so repeated units (e.g. two accuracy panels in a row) aren't shown twice.
        metric_label = METRIC_LABELS.get(metric, metric.upper())
        show_ylabel = metric_label != prev_metric_label
        prev_metric_label = metric_label

        plot_pruning(
            files=files,
            component=component,
            metric=metric,
            other_removed=other_removed,
            title=title,
            percent_metric=True,
            cap=cap,
            ax=ax,
            legend=False,
            open_ended_top=is_error,
            ylabel=show_ylabel,
        )

        # Lock in the ticks the auto locator picks now, while the axes still
        # has its natural size. Otherwise the later tight_layout() call
        # shrinks these axes to make room for the shared legend, and the auto
        # locator re-picks a coarser step (e.g. 20 instead of 10) for the
        # smaller size -- even though the data range hasn't changed.
        # Only keep the ticks actually visible within the current view --
        # get_yticks() also returns off-view candidates (e.g. -10, 70), and
        # fixing those in would let the axes autoscale out to include them.
        lo, hi = ax.get_ylim()
        ax.set_yticks([t for t in ax.get_yticks() if lo <= t <= hi])
        ax.set_ylim(lo, hi)

        if task in ("mmsu", "obqa"):
            lo, hi = ax.get_ylim()
            if hi >= 25:
                ax.axhline(25, color="grey", ls="-.", lw=1.1, zorder=0, label="random guessing")
                ax.set_ylim(lo, hi)  # axhline's autoscale must not stretch the range to fit it

    # One shared legend: dedupe by label across panels (a task can be missing
    # a run's file), keeping first-seen order so it follows RUN's order.
    handles, labels = [], []
    seen = set()
    for ax in axes:
        for h, l in zip(*ax.get_legend_handles_labels()):
            if l not in seen:
                handles.append(h)
                labels.append(l)
                seen.add(l)
    bottom_margin = 0.18 if two_row_legend else 0.1
    fig.tight_layout(rect=(0, bottom_margin, 1, 1))
    ncol = -(-len(handles) // 2) if two_row_legend else len(handles)  # ceil division for 2 rows
    fig.legend(handles, labels, loc="lower center", ncol=ncol, bbox_to_anchor=(0.5, 0.0), fontsize=16)

    if save_path:
        fig.savefig(save_path, dpi=200, format="pdf", bbox_inches="tight")

    return fig


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser()
    parser.add_argument("--component", choices=["enc", "dec"], required=True)
    parser.add_argument("--other_removed", type=int, default=0)
    parser.add_argument("--save_path", default=None)
    args = parser.parse_args()

    results_dir = os.environ.get("RESULTS_DIR")
    if not results_dir:
        raise ValueError("Environment variable RESULTS_DIR is not set")

    save_path = args.save_path or f"{args.component}_performance.pdf"
    save_path = os.path.join(results_dir, save_path)

    plot_all_tasks(
        component=args.component,
        other_removed=args.other_removed,
        results_dir=results_dir,
        save_path=save_path,
    )