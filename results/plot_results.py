""" Plot a pruning metric against the percentage of layers removed.
    Running this codes requires .csv result files, generated by run_stats.sh, to be present.
    run with python plot_results.py --component enc
"""

import csv
import json
import os
import re
from pathlib import Path

import matplotlib.pyplot as plt

plt.rcParams["font.family"] = "serif"
plt.rcParams['mathtext.fontset'] = 'dejavuserif'
plt.rcParams['mathtext.it'] = 'serif:italic'
plt.rcParams['mathtext.rm'] = 'serif'

_KEY = {"enc": "n_enc_removed", "dec": "n_dec_removed"}
_LAYER_KEY = {"enc": "enc_layers", "dec": "dec_layers"}
_NAME_RE = re.compile(r"enc(\d+)_dec(\d+)")


def _read_rows(path):
    """Yield (lineno, dict) from a .csv or .jsonl file. CSV values stay strings."""
    suffix = Path(path).suffix.lower()
    with open(path, newline="") as f:
        if suffix in (".csv", ".tsv"):
            reader = csv.DictReader(f, delimiter="\t" if suffix == ".tsv" else ",")
            for lineno, row in enumerate(reader, 2):  # 1 is the header
                yield lineno, row
        else:
            for lineno, line in enumerate(f, 1):
                line = line.strip()
                if line:
                    yield lineno, json.loads(line)


def _num(value):
    """Cast a CSV string to a number; None if blank or non-numeric."""
    if value is None:
        return None
    if isinstance(value, (int, float)):
        return value
    value = value.strip()
    if value == "" or value.lower() in ("na", "nan", "none", "null"):
        return None
    try:
        return float(value)
    except ValueError:
        return None


def _removed(rec):
    """
    (n_enc_removed, n_dec_removed) for a row.

    Uses explicit columns when present (the old jsonl layout); otherwise reads
    them off the run name, e.g. audioflamingo3_pruned_enc1_dec0 -> (1, 0).
    Returns (None, None) if neither is available.
    """
    enc, dec = _num(rec.get("n_enc_removed")), _num(rec.get("n_dec_removed"))
    if enc is not None and dec is not None:
        return enc, dec

    name = rec.get("model") or rec.get("model_name") or ""
    m = _NAME_RE.search(name)
    if m:
        return float(m.group(1)), float(m.group(2))
    return None, None


def _spec(entry, component, default_layers):
    """Normalise a files[] value into (path, layers_for_this_component)."""
    if isinstance(entry, str):
        return entry, default_layers
    if isinstance(entry, (tuple, list)):
        path, layers = entry
        return path, layers
    if isinstance(entry, dict):
        path = entry["path"]
        layers = entry.get(_LAYER_KEY[component])          # enc_layers / dec_layers
        if layers is None:
            layers = entry.get("total_layers", default_layers)
        return path, layers
    raise TypeError(f"files values must be str, (path, layers) or dict; got {type(entry)}")


METRIC_LABELS = {
    "overall_accuracy": "accuracy",
    "wer": "WER",
}


def _open_ended_top(ax, frac=0.5):
    """
    Push the axes' top limit above the highest tick by `frac` of a tick
    spacing, and lock the ticks so the autolocator doesn't fill the new
    headroom with another one. Used for unbounded metrics (e.g. WER) so the
    top tick visibly sits below the frame instead of touching it -- signalling
    to the reader that the axis isn't capped at that value.
    """
    lo, hi = ax.get_ylim()
    ticks = [t for t in ax.get_yticks() if lo <= t <= hi]
    if len(ticks) < 2:
        return
    ax.set_yticks(ticks)
    step = ticks[-1] - ticks[-2]
    ax.set_ylim(lo, ticks[-1] + step * frac)


def plot_pruning(
    files,
    component,
    metric,
    total_layers=32,
    other_removed=0,
    ax=None,
    title=None,
    percent_metric=False,
    ylim=None,
    cap=None,
    save_path=None,
    legend=True,
    open_ended_top=False,
    ylabel=True,
):
    """
    files          dict: {label: source}, where source is either
                     "path.csv"                              -- uses total_layers
                     ("path.csv", 24)                        -- layers for this component
                     {"path": ..., "enc_layers": 32,
                                   "dec_layers": 28}         -- per-component depths
                   .csv, .tsv and .jsonl are all accepted.
    component      "enc" or "dec" -- which side's removal count drives the x axis.
                   Counts come from n_enc_removed / n_dec_removed columns if
                   present, otherwise from the run name (..._enc1_dec0).
    metric         column / key to read from each row (e.g. "overall_accuracy")
    total_layers   fallback depth for entries that don't carry their own
    other_removed  keep only rows where the *other* component removed this many
                   layers (default 0, so an enc sweep ignores dec-pruned runs).
                   Pass None to keep every row.
    ax             existing matplotlib Axes; a new figure is made if omitted
    percent_metric multiply y values by 100 (for rates like WER stored as 0-1)
    ylim           (low, high) view limits, in the same units as the plotted
                   values -- i.e. after percent_metric scaling. Always applied.
    cap            conditional version of the above: limits become (0, cap)
                   only if some point actually exceeds cap, otherwise the axis
                   autoscales as usual. Ignored when ylim is given. Points left
                   outside run off the axes instead of squashing the rest; how
                   many were clipped is reported per series.
    save_path      if given, write the figure there
    """
    if component not in _KEY:
        raise ValueError(f"component must be 'enc' or 'dec', got {component!r}")
 
    if ax is None:
        _, ax = plt.subplots(figsize=(6, 4))
 
    plotted = {}  # label -> ys, kept so the y range can be decided after reading
 
    for label, entry in files.items():
        path, layers = _spec(entry, component, total_layers)
        if not layers:
            raise ValueError(f"no layer count for {label!r}")
 
        points = []
        for lineno, rec in _read_rows(path):
            enc, dec = _removed(rec)
            if enc is None:
                print(f"[warn] {Path(path).name}:{lineno} no enc/dec counts, skipped")
                continue
            n_removed, n_other = (enc, dec) if component == "enc" else (dec, enc)
            if other_removed is not None and n_other != other_removed:
                continue
 
            y = _num(rec.get(metric))
            if y is None:
                print(f"[warn] {Path(path).name}:{lineno} missing '{metric}'")
                continue
            points.append((100.0 * n_removed / layers, y * 100 if percent_metric else y))
 
        if not points:
            print(f"[warn] no usable points for {label!r} in {path}")
            continue
 
        points.sort()
        xs, ys = zip(*points)
        plot_kwargs = {
            "marker": "o", "markersize": 5, "markeredgewidth": 1.3, "linewidth": 1.1,
            "label": label,
        }
        if isinstance(entry, dict):
            if entry.get("color") is not None:
                plot_kwargs["color"] = entry["color"]
            if entry.get("linestyle") is not None:
                plot_kwargs["linestyle"] = entry["linestyle"]
            if entry.get("marker") is not None:
                plot_kwargs["marker"] = entry["marker"]
        ax.plot(xs, ys, **plot_kwargs)
        plotted[label] = ys
 
    # Explicit ylim wins; otherwise cap only bites when something exceeds it.
    limits = ylim
    if limits is None and cap is not None:
        if any(y > cap for ys in plotted.values() for y in ys):
            limits = (0, cap)
 
    if limits is not None:
        lo, hi = limits
        for label, ys in plotted.items():
            n_out = sum(
                1 for y in ys if (lo is not None and y < lo) or (hi is not None and y > hi)
            )
            if n_out:
                print(f"[warn] {label!r}: {n_out}/{len(ys)} points outside ylim={limits}")
 
    ax.set_xlabel(f"{'encoder' if component == 'enc' else 'decoder'} layers removed (%)", fontsize=14)
    metric_label = METRIC_LABELS.get(metric, metric.upper())
    if ylabel:
        ax.set_ylabel(f"{metric_label} (%)" if percent_metric else metric_label, fontsize=14)
    ax.set_title(title or f"{metric.upper()} vs {component} layers removed", fontsize=16)
    ax.tick_params(axis="both", labelsize=14)
    ax.grid(True, alpha=0.3)
    if limits is not None:
        # set_ylim only fixes the view: out-of-range points leave the axes
        # rather than compressing everything else.
        ax.set_ylim(*limits)
    if open_ended_top:
        _open_ended_top(ax)
    if legend:
        ax.legend(fontsize=14)
    ax.figure.tight_layout()
 
    if save_path:
        ax.figure.savefig(save_path, dpi=200, bbox_inches="tight")
 
    return ax


